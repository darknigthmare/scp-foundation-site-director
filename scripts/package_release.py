"""Package the tested source, playable dist and browser evidence deterministically."""
from datetime import datetime, timezone
from hashlib import sha256
from pathlib import Path
from subprocess import check_output
import json
import os
import zipfile

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "test-results" / "package"
NAME = "scp-builder-operations-spatial-3d-network"


def git(*args):
    return check_output(["git", *args], cwd=ROOT)


def main():
    source_commit = git("rev-parse", "HEAD").decode().strip()
    tracked = git("ls-files", "-z").decode().split("\0")
    files = {name: (ROOT / name).read_bytes() for name in tracked if name and (ROOT / name).is_file()}
    # dist is generated by the immediately preceding build, even when its tracked
    # copy is older; the package must never ship stale compiled code.
    for path in (ROOT / "dist").rglob("*"):
        if path.is_file():
            files[path.relative_to(ROOT).as_posix()] = path.read_bytes()
    report_path = ROOT / "test-results" / "smoke" / "smoke-report.json"
    report = json.loads(report_path.read_text())
    if not report.get("ok") or report.get("browser_messages"):
        raise RuntimeError("Browser verification must succeed before packaging")
    for path in sorted(report_path.parent.iterdir()):
        if path.is_file() and path.suffix in {".json", ".png"} and path.name != "failure.png":
            files[f"release/browser/{path.name}"] = path.read_bytes()
    for name in files:
        parts = Path(name).parts
        if Path(name).is_absolute() or ".." in parts or any(part in {".git", "node_modules", ".vercel"} or part.startswith(".env") for part in parts):
            raise RuntimeError(f"Unexpected private or transient package path: {name}")
    build_info = {
        "gameVersion": json.loads(files["package.json"])["version"],
        "edition": "Operations — Annexes et réseau souterrain 3D",
        "sourceCommit": source_commit,
        "workflowRun": os.environ.get("GITHUB_RUN_ID"),
        "gameSha256": sha256(files["dist/game.js"]).hexdigest(),
        "browserSteps": len(report["steps"]),
        "browserVerification": "passed",
    }
    files["release/BUILD_INFO.json"] = (json.dumps(build_info, ensure_ascii=False, indent=2) + "\n").encode()
    files["release/FILES_SHA256SUMS.txt"] = "".join(f"{sha256(data).hexdigest()}  {name}\n" for name, data in sorted(files.items())).encode()
    epoch = int(git("show", "-s", "--format=%ct", "HEAD").decode().strip())
    date = datetime.fromtimestamp(max(epoch, 315532800), timezone.utc).timetuple()[:6]
    OUT.mkdir(parents=True, exist_ok=True)
    target = OUT / f"{NAME}.zip"
    with zipfile.ZipFile(target, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name, data in sorted(files.items()):
            info = zipfile.ZipInfo(f"{NAME}/{name}", date_time=date)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            archive.writestr(info, data)
    with zipfile.ZipFile(target) as archive:
        invalid = archive.testzip()
        if invalid:
            raise RuntimeError(f"Invalid ZIP entry: {invalid}")
        if archive.read(f"{NAME}/dist/game.js") != files["dist/game.js"]:
            raise RuntimeError("The packaged playable build differs from the tested build")
    digest = sha256(target.read_bytes()).hexdigest()
    (OUT / "SHA256SUMS.txt").write_text(f"{digest}  {target.name}\n")
    (OUT / "BUILD_INFO.json").write_text(json.dumps(build_info, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({"archive": target.name, "sha256": digest, "files": len(files), **build_info}, ensure_ascii=False))


if __name__ == "__main__":
    main()
